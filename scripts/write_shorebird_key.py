from __future__ import annotations

import argparse
import base64
import binascii
import os
import pathlib
import re


PEM_BLOCK_RE = re.compile(
    r"-----BEGIN ([A-Z0-9 ]+)-----\s*(.*?)\s*-----END \1-----",
    re.DOTALL,
)

EXPECTED_LABELS = {
    "public": ("PUBLIC KEY", "RSA PUBLIC KEY"),
    "private": ("PRIVATE KEY", "RSA PRIVATE KEY", "EC PRIVATE KEY"),
}


def normalize_text(value: str) -> str:
    return value.strip().replace("\\n", "\n").replace("\r\n", "\n").replace("\r", "\n")


def has_expected_pem_block(value: str, key_kind: str) -> bool:
    labels = EXPECTED_LABELS[key_kind]
    return any(f"-----BEGIN {label}-----" in value for label in labels) and any(
        f"-----END {label}-----" in value for label in labels
    )


def decode_base64_text(value: str) -> str:
    compact = re.sub(r"\s+", "", value.replace("\\n", ""))
    try:
        decoded = base64.b64decode(compact, validate=True)
    except binascii.Error as exc:
        raise ValueError("value is not valid base64") from exc

    try:
        return normalize_text(decoded.decode("utf-8"))
    except UnicodeDecodeError as exc:
        raise ValueError("base64 value does not decode to UTF-8 PEM text") from exc


def parse_key_material(value: str, key_kind: str) -> str:
    normalized = normalize_text(value)
    if has_expected_pem_block(normalized, key_kind):
        return normalized

    # Windows certutil -encode wraps the base64 payload in CERTIFICATE armor.
    # Some existing secrets were created from that whole output file.
    match = PEM_BLOCK_RE.search(normalized)
    if match:
        decoded = decode_base64_text(match.group(2))
        if has_expected_pem_block(decoded, key_kind):
            return decoded

    decoded = decode_base64_text(normalized)
    if has_expected_pem_block(decoded, key_kind):
        return decoded

    expected = " or ".join(EXPECTED_LABELS[key_kind])
    raise ValueError(f"decoded key is not a {expected} PEM block")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--env", required=True, help="Environment variable containing key material.")
    parser.add_argument("--kind", required=True, choices=("public", "private"))
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    value = os.environ.get(args.env, "")
    if not value.strip():
        raise SystemExit(f"Missing required key material in {args.env}")

    try:
        pem = parse_key_material(value, args.kind)
    except ValueError as exc:
        raise SystemExit(
            f"{args.env} must contain a raw {args.kind} PEM key, a base64-encoded PEM key, "
            f"or the certutil-encoded output generated by older scripts: {exc}"
        ) from exc

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(pem.rstrip() + "\n", encoding="utf-8")
    try:
        output.chmod(0o600)
    except OSError:
        pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
